-- Application schema of POC B. Types match what Hibernate ORM 7 expects on PostgreSQL, because the schema
-- management strategy is "validate" (bdi-config-flyway): the entities and the migrations must agree.
create table settlement_run (
    id          bigint generated by default as identity primary key,
    node        varchar(120) not null,
    started_at  timestamp(6) with time zone not null,
    finished_at timestamp(6) with time zone,
    settled     integer not null,
    rejected    integer not null,
    failed      integer not null
);

create table instruction (
    id             bigint generated by default as identity primary key,
    reference      varchar(35) not null,
    amount         numeric(19, 2) not null,
    status         varchar(20) not null,
    created_at     timestamp(6) with time zone not null,
    settled_at     timestamp(6) with time zone,
    run_id         bigint references settlement_run (id),
    failure_reason varchar(200),
    constraint uk_instruction_reference unique (reference)
);

create index ix_instruction_status on instruction (status);
